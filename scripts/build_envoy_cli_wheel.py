#!/usr/bin/env python3
"""Build a self-contained Envoy CLI wheel that embeds the matching core."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def _source_identity(repo_root: Path) -> tuple[str, bool]:
    revision = subprocess.run(
        ["git", "-C", str(repo_root), "rev-parse", "--short=12", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    )
    source_revision = revision.stdout.strip() if revision.returncode == 0 else "unknown"
    dirty = subprocess.run(
        ["git", "-C", str(repo_root), "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=False,
    )
    return source_revision, dirty.returncode != 0 or bool(dirty.stdout.strip())


def build_wheel(
    repo_root: Path,
    output_dir: Path,
    python_executable: str = sys.executable,
    channel: str = "local-preview",
) -> Path:
    cli_root = repo_root / "packages" / "envoy-cli"
    core_root = repo_root / "packages" / "envoy-core" / "src" / "envoy_core"
    if not cli_root.is_dir() or not core_root.is_dir():
        raise FileNotFoundError("Envoy CLI or core package source was not found")
    if channel not in {"local-preview", "release"}:
        raise ValueError("channel must be local-preview or release")
    output_dir.mkdir(parents=True, exist_ok=True)

    source_revision, source_dirty = _source_identity(repo_root)
    if channel == "release" and source_dirty:
        raise RuntimeError("release wheels require a clean source tree; use local-preview for working changes")
    base_version = re.search(
        r'(?m)^version\s*=\s*"([^"]+)"',
        (cli_root / "pyproject.toml").read_text(encoding="utf-8"),
    )
    if not base_version:
        raise ValueError("Could not find the CLI package version")
    package_version = base_version.group(1)
    if channel == "local-preview":
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")
        package_version = f"{package_version}+preview.g{source_revision}.{timestamp}"

    with tempfile.TemporaryDirectory(prefix="envoy-cli-wheel-") as temporary:
        staging = Path(temporary) / "envoy-cli"
        shutil.copytree(
            cli_root,
            staging,
            ignore=shutil.ignore_patterns("build", "*.egg-info", "__pycache__"),
        )
        shutil.copytree(core_root, staging / "src" / "envoy_core")
        staged_pyproject = staging / "pyproject.toml"
        pyproject_text = staged_pyproject.read_text(encoding="utf-8")
        pyproject_text = re.sub(
            r'(?m)^version\s*=\s*"[^"]+"',
            f'version = "{package_version}"',
            pyproject_text,
            count=1,
        )
        staged_pyproject.write_text(pyproject_text, encoding="utf-8")
        (staging / "src" / "envoy_cli" / "build_info.py").write_text(
            "\n".join((
                '"""Build identity generated by scripts/build_envoy_cli_wheel.py."""',
                "",
                f'BUILD_CHANNEL = "{channel}"',
                f'BUILD_REVISION = "{source_revision}"',
                f"BUILD_DIRTY = {source_dirty!r}",
                f'BUILD_VERSION = "{package_version}"',
                "",
            )),
            encoding="utf-8",
        )
        (staging / "src" / "envoy_cli" / "__init__.py").write_text(
            '"""Independent Envoy command-line reader."""\n\n'
            f'__version__ = "{package_version}"\n',
            encoding="utf-8",
        )
        subprocess.run(
            [
                python_executable,
                "-m",
                "pip",
                "wheel",
                "--no-deps",
                str(staging),
                "--wheel-dir",
                str(output_dir),
            ],
            check=True,
        )

    wheels = sorted(output_dir.glob("envoy_cli-*.whl"), key=lambda item: item.stat().st_mtime)
    if not wheels:
        raise RuntimeError("Wheel build completed without producing envoy_cli wheel")
    return wheels[-1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root",
        default=str(Path(__file__).resolve().parents[1]),
    )
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--python", default=sys.executable, help="Python 3.10+ executable used to build the wheel")
    parser.add_argument(
        "--channel",
        choices=("local-preview", "release"),
        default="local-preview",
        help="Mark the wheel as an isolated local preview or a release artifact",
    )
    args = parser.parse_args()
    try:
        wheel = build_wheel(
            Path(args.repo_root).resolve(),
            Path(args.output_dir).resolve(),
            args.python,
            args.channel,
        )
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"Envoy CLI wheel build failed: {exc}", file=sys.stderr)
        return 2
    print(wheel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
